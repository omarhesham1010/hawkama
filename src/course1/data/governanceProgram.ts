const emptyTimeline: Slide['timeline'] = [];

/** Spoken-only number normalization: Nasser reads round-thousand figures
 *  (like ISO standard numbers) as "٣١ ألف" instead of the raw digit string,
 *  which TTS engines otherwise read out digit-by-digit or awkwardly. Only
 *  applied to narration text — the on-screen card text keeps the raw number
 *  (e.g. "آيزو 31000") untouched. */
function humanizeNumbers(text: string): string {
  return text.replace(/\b(\d{1,3})000\b/g, (_match, n: string) => `${n} ألف`);
}

function quickCheck({
  title,
  text,
  answer,
  rationale,
  tone = 'blue',
}: {
  title: string;
  text: string;
  answer: string;
  rationale: string;
  tone?: PptCard['tone'];
}): PptCard {
  return {
    index: 'تفاعل',
    title,
    text,
    answer,
    rationale,
    tone,
  };
}

function cardWithBullets(card: PptCard, bullets: string[], syncText?: string): PptCard {
  return {
    ...card,
    bullets,
    syncText: syncText ?? card.syncText,
  };
}

function splitBulletCardText(bullet: string): { title: string; text?: string } {
  const colonIndex = bullet.indexOf(':');
  if (colonIndex > -1) {
    const title = bullet.slice(0, colonIndex).trim();
    const text = bullet.slice(colonIndex + 1).trim();
    return { title, text: text || undefined };
  }

  const arrowIndex = bullet.indexOf('←');
  if (arrowIndex > -1) {
    const title = bullet.slice(0, arrowIndex).trim();
    const text = bullet.slice(arrowIndex + 1).trim();
    return { title, text: text || undefined };
  }

  const parenthetical = bullet.match(/^(.+?)\s*\((.+)\)\s*$/);
  if (parenthetical) {
    return { title: parenthetical[1].trim(), text: parenthetical[2].trim() };
  }

  return { title: bullet.trim() };
}

function cardsFromBullets(card: PptCard, bullets: string[], syncText?: string): PptCard[] {
  return bullets.map((bullet, index) => {
    const { title, text } = splitBulletCardText(bullet);

    return {
      ...card,
      index: String(index + 1).padStart(2, '0'),
      title,
      text,
      bullets: undefined,
      spokenDetail: undefined,
      syncText: index === 0 ? syncText ?? title : title,
      tone: index % 2 === 0 ? card.tone : 'gold',
    };
  });
}

function makeSlide({
  id,
  title,
  audioKey,
  narration,
  visual,
  layout,
  cards,
  laterActs,
  actLayouts,
  kind = 'content',
  intro,
  prompt,
  checks,
  courseName,
  subtitle,
  unitTitle,
}: {
  id: string;
  title: string;
  audioKey: string;
  narration: string;
  visual: string;
  layout: PptLayout;
  cards?: PptCard[];
  laterActs?: PptCard[][];
  actLayouts?: PptLayout[];
  kind?: SlideKind;
  intro?: string;
  prompt?: string;
  checks?: PptCard[];
  courseName?: string;
  subtitle?: string;
  unitTitle?: string;
}): Slide {
  // No auto-prepended "topic bridge" here (unlike the original file this
  // was forked from): every narration below is hand-written to state its
  // own topic once, naturally, as its opening line -- an automatic prefix
  // risked doubling up with that opening line (e.g. "موضوعنا الآن هو
  // الخلاصة... وصلنا إلى الخلاصة..."), which reads as a scripting bug, not
  // a professional voice.
  const completeNarration = humanizeNumbers(narration);

  return {
    id,
    index: 0,
    title,
    audioKey,
    narration: completeNarration,
    duration: Math.max(10, Math.ceil(completeNarration.length / 10.5)),
    kind,
    visual,
    layout,
    timeline: emptyTimeline,
    ppt: {
      eyebrow: layout === 'pptIntro' ? 'تحت إشراف المدرب ناصر' : undefined,
      courseName,
      subtitle,
      unitTitle,
      intro,
      prompt,
      cards,
      laterActs,
      actLayouts,
      checks,
    },
  };
}

function indexSlides(items: Slide[]) {
  return items.map((slide, index) => ({ ...slide, index: index + 1 }));
}

function makeQuizSlide({
  id,
  audioKey,
  title,
  narration,
  quiz,
  activityLabel,
  visual = '🧠',
}: {
  id: string;
  audioKey: string;
  title: string;
  narration: string;
  quiz: QuizData;
  activityLabel?: string;
  visual?: string;
}): Slide {
  return {
    id,
    index: 0,
    title,
    audioKey,
    narration,
    duration: Math.max(10, Math.ceil(narration.length / 10.5)),
    kind: 'quiz',
    visual,
    timeline: emptyTimeline,
    activityLabel: activityLabel ?? `اختبار ختامي · ${quiz.questions.length} أسئلة`,
    quiz,
  };
}

function makeChapterClosing({
  id,
  audioKey,
  title,
  narration,
  takeaways,
}: {
  id: string;
  audioKey: string;
  title: string;
  narration: string;
  takeaways: Array<{ title: string; text: string; icon: IconKey }>;
}): Slide {
  return {
    id,
    index: 0,
    title,
    audioKey,
    narration,
    duration: Math.max(10, Math.ceil(narration.length / 10.5)),
    kind: 'completion',
    visual: '🏆',
    timeline: emptyTimeline,
    content: {
      takeaways: {
        kind: 'points',
        variant: 'grid',
        items: takeaways,
      },
    },
  };
}

